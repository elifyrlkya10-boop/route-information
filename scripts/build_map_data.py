#!/usr/bin/env python3
"""Build prototype/map-data.js from data/routes.json and data/photo-spots.json.

The map prototype is opened via file://, where fetch() of local JSON is blocked,
so the data is wrapped as a script: window.MAP_DATA = {...}.

The source JSON files are only read, never modified. Output is deterministic
(no timestamps) so re-running without data changes yields an identical file.

Route fields listed in MAP_EXCLUDED_ROUTE_FIELDS (currently the optional,
unsimplified `pathFull` geometry) are left out of map-data.js so the file stays
small; the map draws the simplified `path`. Modules that need the full
geometry read data/routes.json directly. `geometryRevision` (small; hashes of
`path` and `pathFull` coordinates, see scripts/geometry_revision.py) IS copied,
so map-side code can compare it with dependent data such as photo spots.

Run: python3 scripts/build_map_data.py
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROUTES = ROOT / "data" / "routes.json"
SPOTS = ROOT / "data" / "photo-spots.json"
OUT = ROOT / "prototype" / "map-data.js"

# Fields kept in data/routes.json but not copied to map-data.js.
MAP_EXCLUDED_ROUTE_FIELDS = ("pathFull",)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    routes_doc = json.loads(ROUTES.read_text(encoding="utf-8"))
    spots_doc = json.loads(SPOTS.read_text(encoding="utf-8"))

    routes = routes_doc["routes"]
    spots = spots_doc["photoSpots"]
    route_ids = {r["id"] for r in routes}
    region_ids = {g["id"] for g in routes_doc["regions"]}

    problems = []
    for r in routes:
        if r["regionId"] not in region_ids:
            problems.append(f"{r['id']}: unknown regionId {r['regionId']}")
        if r.get("path", {}).get("type") != "LineString" or len(r["path"].get("coordinates", [])) < 2:
            problems.append(f"{r['id']}: path is not a LineString with >= 2 points")
        full = r.get("pathFull")
        if full is not None:
            coords = full.get("coordinates", [])
            if full.get("type") != "LineString" or len(coords) < 2:
                problems.append(f"{r['id']}: pathFull is not a LineString with >= 2 points")
            elif coords[0] != r["path"]["coordinates"][0] or coords[-1] != r["path"]["coordinates"][-1]:
                problems.append(f"{r['id']}: pathFull does not start/end where path does")
    for s in spots:
        if s["routeId"] not in route_ids:
            problems.append(f"{s['id']}: unknown routeId {s['routeId']}")
    if problems:
        print("Data problems:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1

    payload = {
        "source": {
            "routes": {"file": "data/routes.json", "sha256": sha256(ROUTES)},
            "photoSpots": {"file": "data/photo-spots.json", "sha256": sha256(SPOTS)},
        },
        "countries": routes_doc["countries"],
        "regions": routes_doc["regions"],
        "routes": [
            {k: v for k, v in r.items() if k not in MAP_EXCLUDED_ROUTE_FIELDS}
            for r in routes
        ],
        "photoSpots": spots,
    }
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "// GENERATED by scripts/build_map_data.py - do not edit by hand.\n"
        "// Sources: data/routes.json, data/photo-spots.json\n"
        f"window.MAP_DATA = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(routes)} routes, {len(spots)} photo spots")
    return 0


if __name__ == "__main__":
    sys.exit(main())
